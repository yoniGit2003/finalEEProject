"""The research steps from one place. Run from the repository root:

    python -m research                      the menu: every step in order, what it does, how long it takes
    python -m research run <name>           run one step (names: first column of the menu)
    python -m research run all              run every step in order
    python -m research run all --from <name>    ... starting at <name>
    python -m research compare              compare the tables on disk with the committed ones (after a rerun)
    python -m research docs                 rewrite the step table in docs/REPRODUCE.md from research/steps.yaml

The list of steps is research/steps.yaml (the only place where it is written).
"""
import argparse
import io
import subprocess
import sys
import time
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
STEPS_FILE = REPO / "research" / "steps.yaml"
REPRODUCE = REPO / "docs" / "REPRODUCE.md"
BEGIN, END = "<!-- steps: generated by `python -m research docs`; edit research/steps.yaml instead -->", "<!-- /steps -->"


def load_steps():
    return yaml.safe_load(STEPS_FILE.read_text(encoding="utf-8"))["steps"]


def command(step):
    """The command of a step, as a list: python -m <module> [args]."""
    return [sys.executable, "-m", step["module"], *map(str, step.get("args", []))]


def shown_command(step):
    return " ".join(["python", "-m", step["module"], *map(str, step.get("args", []))])


# ------------------------------------------------------------------------------------------------------- menu
def menu():
    steps = load_steps()
    width = max(len(s["name"]) for s in steps)
    print("Research steps, in run order (python -m research run <name> | all):\n")
    for s in steps:
        report = REPO / s["report"] if s.get("report") else None
        state = "" if report is None else ("report on disk" if report.exists() else "not run yet")
        times = s["time"] + (f" ({s['no_cache']} without the fit caches)" if s.get("no_cache") else "")
        print(f"  {s['name']:<{width}}  {s['what']}")
        print(f"  {'':<{width}}  needs: {', '.join(s.get('needs') or ['earlier steps only'])}; time: {times}"
              + (f"; {state}" if state else ""))
    print("\nData: python pipeline/get_data.py    Fit caches: python pipeline/get_caches.py    "
          "Full instructions: docs/REPRODUCE.md")


# ------------------------------------------------------------------------------------------------------- run
def run(name, start=None):
    steps = load_steps()
    names = [s["name"] for s in steps]
    if name == "all":
        todo = steps[names.index(start):] if start else steps
    elif name in names:
        todo = [steps[names.index(name)]]
    else:
        raise SystemExit(f"unknown step {name!r}; the steps are: {', '.join(names)}")
    for s in todo:
        print(f"\n=== {s['name']}: {shown_command(s)}", flush=True)
        t0 = time.time()
        code = subprocess.run(command(s), cwd=REPO).returncode
        print(f"=== {s['name']}: {'ok' if code == 0 else f'FAILED (exit {code})'} in {time.time() - t0:.0f} s", flush=True)
        if code != 0:
            raise SystemExit(code)


# ------------------------------------------------------------------------------------------------------- compare
def compare(rel_tol):
    """Tables in research/*/outputs/ on disk against the committed version (git HEAD). Reports and figures are not
    compared: reports contain run times, and a figure follows from its table."""
    import numpy as np
    import pandas as pd

    def read(source, name):
        if name.endswith(".parquet"):
            return pd.read_parquet(source)
        return pd.read_csv(source, low_memory=False, compression="gzip" if name.endswith(".gz") else None)

    tracked = subprocess.run(["git", "ls-files", "research"], cwd=REPO, capture_output=True, text=True).stdout.splitlines()
    tables = [f for f in tracked if "/outputs/" in f and f.endswith((".csv", ".csv.gz", ".parquet"))]
    same = differ = 0
    for f in tables:
        path = REPO / f
        if not path.exists():
            print(f"MISSING on disk  {f}")
            differ += 1
            continue
        old_bytes = subprocess.run(["git", "show", f"HEAD:{f}"], cwd=REPO, capture_output=True).stdout
        if old_bytes == path.read_bytes():
            same += 1
            continue
        old, new = read(io.BytesIO(old_bytes), f), read(path, f)
        notes = []
        if list(old.columns) != list(new.columns) or len(old) != len(new):
            notes.append(f"shape {old.shape} -> {new.shape}")
        else:
            for c in old.columns:
                a, b = old[c], new[c]
                if pd.api.types.is_numeric_dtype(a) and pd.api.types.is_numeric_dtype(b):
                    a, b = a.to_numpy(float), b.to_numpy(float)
                    bad = ~np.isclose(a, b, rtol=rel_tol, atol=0.0, equal_nan=True)
                    if bad.any():
                        notes.append(f"{c}: {int(bad.sum())} values, largest difference {np.nanmax(np.abs(a - b)[bad]):.3g}")
                else:
                    a = a.astype(object).where(a.notna(), "").astype(str)
                    b = b.astype(object).where(b.notna(), "").astype(str)
                    if (a != b).any():
                        notes.append(f"{c}: {int((a != b).sum())} cells")
        if notes:
            differ += 1
            print(f"DIFFERENT  {f}: " + "; ".join(notes[:5]) + (" ..." if len(notes) > 5 else ""))
        else:
            same += 1
    print(f"\n{same} tables equal to the committed version (relative tolerance {rel_tol:g}), {differ} different")


# ------------------------------------------------------------------------------------------------------- docs
def step_table():
    rows = ["| # | step | command | what it does | needs | time | without caches |", "|---|---|---|---|---|---|---|"]
    for i, s in enumerate(load_steps(), 1):
        was = f", was {s['old_id']}" if s.get("old_id") else ""
        label = s["name"] + (f" (step {s['id']}{was})" if s.get("id") else "")
        rows.append(f"| {i} | {label} | `{shown_command(s)}` | {s['what']} | {', '.join(s.get('needs') or ['-'])} "
                    f"| {s['time']} | {s.get('no_cache', '-')} |")
    return "\n".join(rows)


def docs(check=False):
    """Put the step table into docs/REPRODUCE.md, between the two marker lines. --check: only say if it is stale."""
    text = REPRODUCE.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{REPRODUCE}: the marker lines are missing")
    head, rest = text.split(BEGIN, 1)
    new = head + BEGIN + "\n" + step_table() + "\n" + END + rest.split(END, 1)[1]
    if new == text:
        print("docs/REPRODUCE.md is up to date")
        return 0
    if check:
        print("docs/REPRODUCE.md is OUT OF DATE: run `python -m research docs`")
        return 1
    REPRODUCE.write_text(new, encoding="utf-8", newline="\n")
    print("docs/REPRODUCE.md updated")
    return 0


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(prog="python -m research", description="Run and list the research steps.")
    sub = parser.add_subparsers(dest="action")
    p_run = sub.add_parser("run", help="run one step, or all of them in order")
    p_run.add_argument("name", help="a step name, or `all`")
    p_run.add_argument("--from", dest="start", help="with `all`: start at this step")
    p_cmp = sub.add_parser("compare", help="compare the tables on disk with the committed ones")
    p_cmp.add_argument("--tolerance", type=float, default=1e-9, help="relative tolerance (default 1e-9)")
    p_docs = sub.add_parser("docs", help="rewrite the step table in docs/REPRODUCE.md")
    p_docs.add_argument("--check", action="store_true", help="only check; exit 1 if the table is out of date")
    args = parser.parse_args()
    if args.action == "run":
        run(args.name, args.start)
    elif args.action == "compare":
        compare(args.tolerance)
    elif args.action == "docs":
        sys.exit(docs(args.check))
    else:
        menu()


if __name__ == "__main__":
    main()
